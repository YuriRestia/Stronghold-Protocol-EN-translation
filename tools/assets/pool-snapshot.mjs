#!/usr/bin/env node
// (fork) The audio pool snapshot that test/audio-pools-data.test.js holds data/assets.json to: how many attack / hit
// sound references each unit and outfit has, and how many sounds each pool (official bank) has, one entry per line.
// Before, the test held three literal totals; two branches that each added sounds then always conflicted on the same
// numbers. One line per unit and per pool lets git merge branches that touch different operators, and
// tools/merge-generated.mjs merges the rest (docs/ASSETS.md "Merging branches").
//
//   node tools/assets/pool-snapshot.mjs           check: exit 1 and list the differences when the snapshot is stale
//   node tools/assets/pool-snapshot.mjs --update  rewrite the snapshot from data/assets.json
import { readFileSync, writeFileSync, renameSync, realpathSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const MANIFEST_PATH = join(ROOT, 'data', 'assets.json');
export const SNAPSHOT_PATH = join(ROOT, 'test', 'audio-pools-data.snapshot.json');
const ABOUT = 'Generated by tools/assets/pool-snapshot.mjs --update from data/assets.json; test/audio-pools-data.test.js holds the manifest to it.';
/** The snapshot is a few hundred kB; anything far bigger is a bug, not a snapshot (storage rule: every write is capped). */
const MAX_BYTES = 8 * 1024 * 1024;

const sortKeys = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));

/**
 * The attack / hit references of one sound entry (a unit's or an outfit's) as [role, url, poolId] rows: the
 * normal slots (`attack`, `hit` with `pools`), and the per-skill ones (`attacks` with `attackPools`, `hits` with
 * `hitPools`). Empty urls are no reference.
 * @param {any} u
 */
export function soundRefs(u) {
  const out = [];
  for (const [urls, ids, tag] of [[{ attack: u.attack, hit: u.hit }, u.pools, ''], [u.attacks, u.attackPools, 'attacks.'], [u.hits, u.hitPools, 'hits.']]) {
    for (const [role, url] of Object.entries(urls || {})) if (url) out.push([tag + role, url, ids?.[role]]);
  }
  return out;
}

/**
 * The snapshot of a manifest: reference counts per unit and per outfit (units without one are left out) and the
 * number of sounds of every pool.
 * @param {any} manifest data/assets.json
 */
export function poolSnapshot(manifest) {
  const { units = {}, outfits = {}, pools = {} } = manifest?.audio?.sfx || {};
  const count = (map) => {
    const out = {};
    for (const [id, u] of Object.entries(map)) { const n = soundRefs(u).length; if (n) out[id] = n; }
    return sortKeys(out);
  };
  const poolSizes = {};
  for (const [id, p] of Object.entries(pools)) poolSizes[id] = Object.keys(p?.sounds || {}).length;
  return { about: ABOUT, refs: count(units), outfitRefs: count(outfits), pools: sortKeys(poolSizes) };
}

/** The file text: one entry per line, so git merges branches that touch different units or pools. */
export function formatSnapshot(snap) {
  return JSON.stringify({ about: ABOUT, refs: sortKeys(snap.refs || {}), outfitRefs: sortKeys(snap.outfitRefs || {}), pools: sortKeys(snap.pools || {}) }, null, 2) + '\n';
}

/**
 * Differences between two snapshots, as readable lines (`refs char_x: 3 → 4`, `pools y: (none) → 2`); empty = equal.
 * @param {any} want the committed snapshot
 * @param {any} got the manifest's
 */
export function diffSnapshots(want, got) {
  const lines = [];
  for (const part of ['refs', 'outfitRefs', 'pools']) {
    const a = want?.[part] || {}, b = got?.[part] || {};
    for (const k of [...new Set([...Object.keys(a), ...Object.keys(b)])].sort()) {
      if (a[k] !== b[k]) lines.push(`${part} ${k}: ${a[k] ?? '(none)'} → ${b[k] ?? '(none)'}`);
    }
  }
  return lines;
}

/** Totals, for messages: references, outfit references, pools. */
export function snapshotTotals(snap) {
  const sum = (o) => Object.values(o || {}).reduce((s, n) => s + n, 0);
  return { refs: sum(snap.refs), outfitRefs: sum(snap.outfitRefs), pools: Object.keys(snap.pools || {}).length };
}

/** Write the snapshot of `manifestPath` to `snapshotPath` (atomic, size-capped). */
export function writeSnapshot(manifestPath = MANIFEST_PATH, snapshotPath = SNAPSHOT_PATH) {
  const text = formatSnapshot(poolSnapshot(JSON.parse(readFileSync(manifestPath, 'utf8'))));
  if (Buffer.byteLength(text) > MAX_BYTES) throw new Error(`pool snapshot would be ${Buffer.byteLength(text)} bytes (cap ${MAX_BYTES}); not written`);
  writeFileSync(snapshotPath + '.tmp', text);
  renameSync(snapshotPath + '.tmp', snapshotPath);
  return text;
}

const invoked = (() => { try { return pathToFileURL(realpathSync(process.argv[1] || '')).href; } catch { return null; } })();
if (invoked === import.meta.url) {
  if (process.argv.includes('--update')) {
    const t = snapshotTotals(JSON.parse(writeSnapshot()));
    console.log(`pool-snapshot: wrote ${SNAPSHOT_PATH} (${t.refs} references, ${t.outfitRefs} outfit references, ${t.pools} pools)`);
  } else {
    const got = poolSnapshot(JSON.parse(readFileSync(MANIFEST_PATH, 'utf8')));
    let want = null;
    try { want = JSON.parse(readFileSync(SNAPSHOT_PATH, 'utf8')); } catch { /* missing or unreadable: every entry differs */ }
    const diff = diffSnapshots(want, got);
    if (diff.length) {
      console.log(`pool-snapshot: ${diff.length} difference(s) between data/assets.json and the snapshot:\n  ${diff.slice(0, 50).join('\n  ')}${diff.length > 50 ? `\n  … ${diff.length - 50} more` : ''}\nRun: npm run assets:pool-snapshot -- --update`);
      process.exitCode = 1;
    } else console.log('pool-snapshot: up to date');
  }
}
