"""(fork) The skills whose cast plays a begin clip first, read from the CN client: tools/assets/skill-begin-anims.mjs.

The client's skill cast (Character.States.SkillState.OnEnter -> BasicSkill.OnBeforeSkillStart) plays the skill's
`_beginAnim` when its root behaviour sets `_playSkillBeginAnim` (BasicSkill.PlayBeginAnimation: the owner's
PlayAnimation at time scale 1, WaitForFixedSeconds(the clip's length), then DoStartSkill). The skill starts, and the
character attacks again, only when that clip ends; leaving the Skill state first (stun, death …: SkillState.OnExit ->
InterruptStartIfNot) drops the cast. A skill with a chant behaviour (ChantBeforeSkill or a subclass: BasicSkill.hasChant)
runs that chant in place of PlayBeginAnimation and starts when the chant ends, so it is left out (a chant that plays the
clip itself, ChantWithProjectileBeforeSkill `_afterEndAnim`, is its kit's to time). This script lists those skills from
battle/prefabs/[uc]skills.ab; the data build
(tools/build-data.mjs operatorBeginAnims) times each with its clip in the operator's default model.

    .venv-extract/Scripts/python.exe -I -B tools/skill_begin.py [--ab <extracted bundles root>]

The bundles root is the local extract's (`.cache/ab-cn`, docs/ASSETS.md). The output is committed; rerun after a client
update and review the diff.
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
# a maintainer tool, kept out of tools/local-extract/ (which ships to players) because it writes a committed table; it
# borrows that folder's bundle reader
sys.path.insert(0, str(HERE / 'local-extract'))
import fx  # noqa: E402

OUT = ROOT / 'tools/assets/skill-begin-anims.mjs'

HEADER = '''// GENERATED by tools/skill_begin.py from the CN client's battle/prefabs/[uc]skills.ab — do not edit.
// (fork) Every skill whose root behaviour sets `_playSkillBeginAnim`: its cast plays `begin` (`_beginAnim`; `down`:
// `_beginAnimDown`, the facing-down variant, null when the skill names none) and the skill starts when that clip ends
// (BasicSkill.PlayBeginAnimation → DoStartSkill). Read by tools/build-data.mjs operatorBeginAnims.
'''


def begin_skills(ab_root):
    """{skill id: {'begin': clip, 'down': clip or None}} of every [uc]skills.ab skill that plays a begin clip."""
    env = fx.AssetEnv(ab_root, {})
    out = {}
    for sid, go in env.prefabs(fx.SKILLS).items():
        row, chant = None, False
        for c in env.tt(go).get('m_Component', []):
            f, o = env.resolve(go.assets_file, c.get('component'))
            if o is None or f == 'builtin' or o.type.name != 'MonoBehaviour':
                continue
            d = env.tt(o)
            if d.get('_playSkillBeginAnim') and d.get('_beginAnim'):
                row = {'begin': d['_beginAnim'], 'down': d.get('_beginAnimDown') or None}
            # a ChantBeforeSkill (or subclass) behaviour: BasicSkill.hasChant (m_chantBehavior != null) makes
            # OnBeforeSkillStart run the chant instead of PlayBeginAnimation, and the chant's end calls DoStartSkill
            if '_buffsWhenStartChant' in d:
                chant = True
        if row and not chant:
            out[sid] = row
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--ab', default=str(ROOT / '.cache/ab-cn'), help='extracted bundles root (default .cache/ab-cn)')
    a = ap.parse_args()
    rows = begin_skills(Path(a.ab))
    lines = [HEADER, 'export const SKILL_BEGIN_ANIMS = Object.freeze({']
    for sid in sorted(rows):
        r = rows[sid]
        lines.append(f"  {json.dumps(sid)}: Object.freeze({{ begin: {json.dumps(r['begin'])}, down: {json.dumps(r['down'])} }}),")
    lines.append('});\n')
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'{len(rows)} skills -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
